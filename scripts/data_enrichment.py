def main():
    # --- Drug Interactions ---
    conn = sqlite3.connect(os.path.join(BASE_DIR, "clinic_codes.db"))
    existing_pairs = set()
    for r in conn.execute("SELECT drug_a, drug_b FROM drug_interactions"):
        existing_pairs.add((r[0], r[1]))
        existing_pairs.add((r[1], r[0]))

    added_di = 0
    for row in NEW_DRUG_INTERACTIONS:
        if (row[0], row[1]) not in existing_pairs and (row[1], row[0]) not in existing_pairs:
            conn.execute(
                "INSERT INTO drug_interactions (drug_a, drug_b, severity, category, description, mechanism, clinical_effect, management, evidence_level, source) VALUES (?,?,?,?,?,?,?,?,?,?)",
                row)
            existing_pairs.add((row[0], row[1]))
            added_di += 1
    conn.commit()
    total_di = conn.execute("SELECT COUNT(*) FROM drug_interactions").fetchone()[0]
    print(f"Drug Interactions: +{added_di}건 (총 {total_di}건)")

    # --- Denial Reasons ---
    existing_codes = set(r[0] for r in conn.execute("SELECT denial_code FROM denial_reasons"))
    added_dr = 0
    for row in NEW_DENIAL_REASONS:
        if row[0] not in existing_codes:
            conn.execute(
                "INSERT INTO denial_reasons (denial_code, category, subcategory, description, common_codes, response_template, response_evidence, success_rate, prevention_tip, source) VALUES (?,?,?,?,?,?,?,?,?,?)",
                (*row, "심사 기준"))
            existing_codes.add(row[0])
            added_dr += 1
    conn.commit()
    total_dr = conn.execute("SELECT COUNT(*) FROM denial_reasons").fetchone()[0]
    print(f"Denial Reasons: +{added_dr}건 (총 {total_dr}건)")
    conn.close()

    # --- Medical Knowledge (RAG) ---
    conn2 = sqlite3.connect(os.path.join(BASE_DIR, "medical.db"))
    existing_ids = set(r[0] for r in conn2.execute("SELECT id FROM medical_knowledge"))
    added_rag = 0
    for row in NEW_MEDICAL_KNOWLEDGE:
        if row[0] not in existing_ids:
            conn2.execute(
                "INSERT INTO medical_knowledge (id, title, category, content, source) VALUES (?,?,?,?,?)",
                row)
            existing_ids.add(row[0])
            added_rag += 1
    conn2.commit()
    total_rag = conn2.execute("SELECT COUNT(*) FROM medical_knowledge").fetchone()[0]
    print(f"Medical Knowledge (RAG): +{added_rag}건 (총 {total_rag}건)")
    conn2.close()

    print("\nDone!")


if __name__ == "__main__":
    main()
