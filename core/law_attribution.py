"""법령명 오귀속 탐지 — **답변이 댄 법령이 근거에 있는가**.

충실도 judge는 주장의 *내용*을 근거와 대조할 뿐 **어느 법률의 조문인가**는 판정 축에
없다. 2026-08-18 A/B에서 그 사각이 드러났다 — 법령명 오귀속 8건 중 **7건이
`faith 1.000 · 환각 없음`으로 통과**했고, 한 답변은 "법률명: 국민건강보험법"이라고
라벨까지 달아 놓고 만점이었다(정답은 「의료법」 제58조의3).

⇒ 이 축은 **결정적 계산**으로만 잡힌다. LLM을 쓰지 않는다(v2.124.74에서 형식 판정을
   judge에서 순수 함수로 옮긴 것과 같은 분업 — judge=의미, 메트릭=형식).

🔴 **v1은 통제군 7/7을 통과하고도 실전에서 위양성 4건을 냈다.**
   근거 청크의 `law_name`과 대조했는데, **법령 본문이 다른 법을 정당하게 인용**하는
   경우를 못 봤기 때문이다. 그 법은 `law_name`엔 없고 **본문엔 있다**:

       의료법 제82조①  … 「장애인복지법」에 따른 시각장애인 …
       의료법 제23조①  … 「전자서명법」에 따른 전자서명 …
       의료법 제17조의2 … 「노인복지법」 제34조에 따른 시설 종사자 …

   ⇒ **근거 본문 전체**와 대조한다. 통제군에도 이 패턴을 넣어 고정했다
     (`tests/test_law_attribution.py`) — 통제군이 실전 분포를 안 덮으면
     통과가 보증이 되지 않는다.

실측(2026-08-18 · A/B 답변 각 40건 · 앞 400자):
    qwen3.6:35b-a3b(프로덕션)  0/40
    qwen3-vl:30b-a3b(기각 후보) 3/40   ← `국민건강보험법`×2 · **`의료인법`**(실재하지 않는 법률명)
"""
from __future__ import annotations

import re

__author__ = "신현묵 <8508132+seanshin@users.noreply.github.com>"

# 「…법」 또는 맨몸 "…법" + 조문/조사가 뒤따르는 경우.
# 파일명·고시명 안의 토큰은 앞에 `_`·`-`·한글이 붙어 있어 경계 조건에서 걸러진다.
_LAW_RE = re.compile(
    r"「\s*([가-힣ㆍ·\s]{2,24}?법)\s*(?:시행령|시행규칙)?\s*」"
    r"|(?<![가-힣_\-])([가-힣ㆍ·]{2,12}법)(?:\s*시행령|\s*시행규칙)?"
    r"(?=\s*제\d|\s*[에의은는이가을를,.\s]|$)"
)
_WS = re.compile(r"\s+")

# 법령명이 아닌 흔한 오검출(일반명사가 '법'으로 끝나는 경우)
_NOT_A_LAW = frozenset({
    "이법", "본법", "동법", "해당법", "관계법", "관련법", "현행법", "국내법", "방법", "요법", "용법",
})


def _norm(text: str) -> str:
    return _WS.sub("", text or "")


def cited_laws(answer: str) -> list[str]:
    """답변이 인용한 법령명(중복 제거·등장 순). 시행령·시행규칙은 모법으로 접는다."""
    out: list[str] = []
    for m in _LAW_RE.finditer(answer or ""):
        name = _norm(m.group(1) or m.group(2))
        if not name or name in _NOT_A_LAW or name in out:
            continue
        out.append(name)
    return out


# 근거가 **법령명 라벨**을 싣고 있는지. `/ask` 생성 컨텍스트는
# `[권위:…] [의료법 시행규칙 제15조(진료기록부 등의 보존)]` 형태로 붙이지만,
# 평가 근거(`EF.get_evidence()`)는 **조문 본문만** 준다.
_LABEL_RE = re.compile(r"\[권위:|\[[^\]]{0,20}법[^\]]{0,40}제\d+조|\[발간물\(")
#: 발간물 라벨 — `law_name`이 문서 제목이라 법령명 매칭에서 빼야 한다.
_PUB_LABEL_RE = re.compile(r"\[발간물\([^\]]*\][^\n]*")


def evidence_has_law_labels(evidence: str) -> bool:
    """근거가 법령명 라벨을 실었는가 — 아니면 귀속을 판정할 수 없다."""
    return bool(_LABEL_RE.search(evidence or ""))


def misattributed(answer: str, evidence: str) -> list[str]:
    """근거 **본문 어디에도 없는** 법령명 목록. 비었으면 오귀속 없음.

    ⚠️ 근거를 통째로 넘길 것 — `law_name` 메타만 넘기면 v1의 위양성이 재발한다.

    🔴 2026-08-18: 근거에 **법령명 라벨이 없으면 판정하지 않는다**(fail-open).
       평가 근거는 조문 본문만이라 `의료법`이라는 문자열이 아예 없고(실측 15/40),
       그 상태로 세면 **정확한 인용이 오귀속으로** 잡힌다(기준선 배치 22/40 전부 위양성).
       근거 표현이 라벨을 싣게 되면 이 가드가 자동으로 풀린다.
    """
    if not evidence_has_law_labels(evidence):
        return []                      # 라벨이 없으면 귀속을 판정할 근거가 없다
    # ⚠️ 발간물 라벨은 **문서 제목**이다(「국민건강보험법령집」 등). 이걸 남겨 두면
    #    "국민건강보험법"이 부분문자열로 걸려 **오귀속을 정상으로** 세게 된다
    #    (v2.124.8이 봉합한 그 오인의 탐지기 판). 매칭 전에 지운다.
    ev = _norm(_PUB_LABEL_RE.sub(" ", evidence or ""))
    if not ev:
        return []                      # 근거가 없으면 판정하지 않는다(fail-open)
    return [c for c in cited_laws(answer) if c not in ev]
